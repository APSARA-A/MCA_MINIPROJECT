# Local MVP whole-blood pre-screening policy, subject to facility approval.
# These values are not universal clinical eligibility rules.
MATCHING_MIN_AGE = int(os.getenv('MATCHING_MIN_AGE', '18'))
MATCHING_MAX_AGE = int(os.getenv('MATCHING_MAX_AGE', '60'))
MATCHING_MIN_WEIGHT_KG = (
    float(os.environ['MATCHING_MIN_WEIGHT_KG']) if os.getenv('MATCHING_MIN_WEIGHT_KG') else None
)
MATCHING_WHOLE_BLOOD_INTERVAL_DAYS = {
    'MALE': int(os.getenv('MATCHING_MALE_INTERVAL_DAYS', '90')),
    'FEMALE': int(os.getenv('MATCHING_FEMALE_INTERVAL_DAYS', '120')),
}

# Fail early for invalid policy configuration rather than quietly bypassing checks.
from math import isfinite
if not (0 <= MATCHING_MIN_AGE <= MATCHING_MAX_AGE):
    raise ImproperlyConfigured("MATCHING age bounds must be nonnegative and ordered.")
if any(days <= 0 for days in MATCHING_WHOLE_BLOOD_INTERVAL_DAYS.values()):
    raise ImproperlyConfigured("MATCHING whole-blood intervals must be positive day counts.")
if MATCHING_MIN_WEIGHT_KG is not None and (
    not isfinite(MATCHING_MIN_WEIGHT_KG) or MATCHING_MIN_WEIGHT_KG <= 0
):
    raise ImproperlyConfigured("MATCHING_MIN_WEIGHT_KG must be a finite positive number.")

